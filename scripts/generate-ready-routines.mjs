#!/usr/bin/env node
// Builds the ready-made routines (src/lib/training/ready-routines.ts) with the plan engine and
// writes supabase/migrations/20261014092000_ready_routines.sql. Idempotent: fixed ids, upserts.
// Usage: node scripts/generate-ready-routines.mjs

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const esbuild = await import(process.env.ESBUILD_PATH ?? 'esbuild');
const bundle = path.join(os.tmpdir(), `startfit-ready-${process.pid}.mjs`);
await esbuild.build({
  stdin: {
    contents: [
      "export { READY_ROUTINES } from './src/lib/training/ready-routines.ts';",
      "export { generatePlan } from './src/lib/training/engine.ts';",
      "export { validatePlan, usableContextFor } from './src/lib/training/validate.ts';",
      "export { screenForTraining } from './src/lib/training/screening.ts';",
      "export { testLibrary, baseIntake } from './src/lib/training/test-fixtures.ts';",
      "export { EQUIPMENT_PRESETS } from './src/lib/training/engine-library.ts';",
      "export { routineRowsFromPlan } from './src/lib/training/routine.ts';",
    ].join('\n'),
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: bundle,
  alias: { '@': path.join(root, 'src') },
  loader: { '.json': 'json' },
  logLevel: 'error',
});

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const uuidFor = (slug) => {
  const h = crypto.createHash('sha1').update(`startfit-ready-routine:${slug}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const GOAL = { muscle: 'muscle_gain', strength: 'strength', fat_loss: 'fat_loss', general: 'general_fitness', endurance: 'endurance' };

try {
  const m = await import(pathToFileURL(bundle).href);
  const lib = m.testLibrary();
  const out = [];
  out.push(`/*
# Ready-made routines (generated: do not edit by hand)

Generated by scripts/generate-ready-routines.mjs from src/lib/training/ready-routines.ts. Each routine
is built by the StartFit plan engine for a typical healthy adult (age 30, no health conditions or
pain, exercising regularly) with the stated goal, experience, schedule and equipment, so it follows
the same evidence and rules as a personal plan. The full plan (weekly volume, reasons, references)
is stored in workout_plans.details. Needs 20261014090000_training_library.sql and
20261014091000_training_brain.sql.
*/
`);
  const ids = [];
  for (const spec of m.READY_ROUTINES) {
    const intake = m.baseIntake({
      goal: spec.goal,
      experience: spec.level,
      daysPerWeek: spec.days,
      sessionMinutes: spec.minutes,
      equipment: m.EQUIPMENT_PRESETS[spec.equipment].tags,
      currentActivity: 'regular',
    });
    const r = m.generatePlan(intake, lib, { now: new Date('2026-10-14T00:00:00Z') });
    if (r.status !== 'ready') throw new Error(`${spec.slug}: held`);
    const screening = m.screenForTraining(intake);
    const errors = m.validatePlan(r.plan, lib, m.usableContextFor(intake, screening), screening).filter((i) => i.level === 'error');
    if (errors.length) throw new Error(`${spec.slug}: ${errors[0].message}`);
    const plan = { ...r.plan, title: spec.name };
    const id = uuidFor(spec.slug);
    ids.push(id);
    const description = `${plan.summary} A general template for healthy adults: build your own plan in the Training coach to fit your health, schedule and equipment.`;
    out.push(`-- ${spec.name}`);
    out.push(
      `INSERT INTO public.workout_plans (id, name, description, goal, difficulty, duration_weeks, sessions_per_week, session_duration_min, equipment_needed, is_public, created_by, details, source)
VALUES (${q(id)}, ${q(spec.name)}, ${q(description)}, ${q(GOAL[plan.effectiveGoal])}, ${q(plan.level === 'new' ? 'beginner' : plan.level)}, 6, ${plan.strengthDays}, ${plan.sessionMinutes}, ARRAY[${plan.equipmentUsed.map(q).join(', ')}]::text[], true, NULL, ${q(JSON.stringify(plan))}::jsonb, 'library')
ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, description = EXCLUDED.description, goal = EXCLUDED.goal, difficulty = EXCLUDED.difficulty,
  duration_weeks = EXCLUDED.duration_weeks, sessions_per_week = EXCLUDED.sessions_per_week, session_duration_min = EXCLUDED.session_duration_min,
  equipment_needed = EXCLUDED.equipment_needed, is_public = true, details = EXCLUDED.details, source = 'library', archived = false;`,
    );
    out.push(`DELETE FROM public.workout_plan_exercises WHERE plan_id = ${q(id)};`);
    const rows = m.routineRowsFromPlan(plan);
    out.push(
      `INSERT INTO public.workout_plan_exercises (plan_id, exercise_id, exercise_order, sets, reps, rest_seconds, day_index, day_label, rir_target, notes)
SELECT ${q(id)}, e.id, v.exercise_order, v.sets, v.reps, v.rest_seconds, v.day_index, v.day_label, v.rir_target, v.notes
FROM (VALUES
${rows.map((x) => `  (${q(x.exercise_id)}, ${x.exercise_order}, ${x.sets}, ${q(x.reps)}, ${x.rest_seconds}, ${x.day_index}, ${q(x.day_label)}, ${x.rir_target == null ? 'NULL::int' : x.rir_target}, ${x.notes == null ? 'NULL::text' : q(x.notes)})`).join(',\n')}
) AS v(source_id, exercise_order, sets, reps, rest_seconds, day_index, day_label, rir_target, notes)
JOIN public.exercises e ON e.source_id = v.source_id;
`,
    );
  }
  out.push(`-- Every ready-made routine must have all of its exercises.
DO $$
DECLARE missing int;
BEGIN
  SELECT count(*) INTO missing FROM public.workout_plans p
  WHERE p.id IN (${ids.map(q).join(', ')})
    AND NOT EXISTS (SELECT 1 FROM public.workout_plan_exercises pe WHERE pe.plan_id = p.id);
  IF missing > 0 THEN RAISE EXCEPTION 'Ready-made routines without exercises: %', missing; END IF;
END $$;
`);
  const file = path.join(root, 'supabase/migrations/20261014092000_ready_routines.sql');
  fs.writeFileSync(file, out.join('\n'));
  console.log(`Wrote ${path.relative(root, file)}: ${ids.length} routines.`);
} finally {
  fs.rmSync(bundle, { force: true });
}
