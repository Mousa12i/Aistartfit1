#!/usr/bin/env node
// Regenerates the exercise-library migration from the reviewed sources:
//   data/free-exercise-db.json      open dataset (public domain, github.com/yuhonas/free-exercise-db)
//   data/startfit-catalog.json      the app's original catalogue (from the earlier migrations)
//   src/lib/training/*.ts           taxonomy, hand review (library-overrides.ts), additions, curated core
//
// Usage: node scripts/generate-training-library.mjs
// Writes supabase/migrations/20261014090000_training_library.sql. Run it again after editing any
// of the files above; the migration is idempotent and can be applied to a database that already
// has the library.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const esbuild = await import(process.env.ESBUILD_PATH ?? 'esbuild');
const bundle = path.join(os.tmpdir(), `startfit-library-${process.pid}.mjs`);

await esbuild.build({
  stdin: {
    contents: "export { buildLibrary } from './src/lib/training/library-build.ts';\nexport { librarySql } from './src/lib/training/library-sql.ts';\nexport { CORE_SLOTS } from './src/lib/training/curated.ts';",
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: bundle,
  alias: { '@': path.join(root, 'src') },
  logLevel: 'error',
});

try {
  const { buildLibrary, librarySql, CORE_SLOTS } = await import(pathToFileURL(bundle).href);
  const dataset = JSON.parse(fs.readFileSync(path.join(root, 'data/free-exercise-db.json'), 'utf8'));
  const catalog = JSON.parse(fs.readFileSync(path.join(root, 'data/startfit-catalog.json'), 'utf8'));
  const { entries, byKey } = buildLibrary(dataset, catalog);
  const visible = entries.filter((e) => !e.hidden).length;
  const header = `/*
# Exercise library (generated: do not edit by hand)

Generated by scripts/generate-training-library.mjs from data/free-exercise-db.json,
data/startfit-catalog.json and src/lib/training/ (taxonomy.ts, library-overrides.ts,
library-additions.ts, curated.ts).

${entries.length} exercises: ${visible} visible in the library, ${entries.length - visible} hidden (duplicates kept for old
routines and logs, or source entries with no instructions).

Every exercise gets a movement pattern, the muscles it trains directly (primary, counted as one
set) and indirectly (secondary, counted as half a set), equipment, safety tags and a starting
prescription. exercise_muscles (used by the recovery model) is kept in step by a trigger.
Also fixes exercise access rules: library rows become read-only and custom exercises private.
*/`;
  const sql = librarySql(entries, byKey, header);
  const out = path.join(root, 'supabase/migrations/20261014090000_training_library.sql');
  fs.writeFileSync(out, sql);

  // Curated key ("D:Barbell Squat") -> library source id, so the plan engine can find each curated
  // exercise in the database without shipping the 1 MB dataset to the browser.
  const keys = [...new Set(Object.values(CORE_SLOTS).flatMap((slot) => slot.candidates.map((cand) => cand.key)))].sort();
  const idx = Object.fromEntries(keys.map((k) => [k, byKey.get(k).sourceId]));
  const idxOut = path.join(root, 'src/lib/training/curated-index.generated.ts');
  fs.writeFileSync(
    idxOut,
    `// Generated by scripts/generate-training-library.mjs: do not edit by hand.\n` +
      `// Maps each curated exercise key (see curated.ts) to its library source_id.\n` +
      `export const CURATED_SOURCE_IDS: Record<string, string> = ${JSON.stringify(idx, null, 2)};\n`,
  );
  console.log(`Wrote ${path.relative(root, out)} (${(sql.length / 1024).toFixed(0)} KB): ${entries.length} exercises, ${visible} visible.`);
} finally {
  fs.rmSync(bundle, { force: true });
}
