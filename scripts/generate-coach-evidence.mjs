#!/usr/bin/env node
// Copies the evidence lists into the coach server functions, so each coach and the app always cite
// exactly the same claims:
//   src/lib/training/evidence.ts         -> supabase/functions/training-coach/evidence.generated.ts
//   src/lib/recovery/doctor/evidence.ts  -> supabase/functions/recovery-coach/evidence.generated.ts
// Usage: node scripts/generate-coach-evidence.mjs   (run again after editing evidence.ts)

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const esbuild = await import(process.env.ESBUILD_PATH ?? 'esbuild');
const TARGETS = [
  { src: 'src/lib/training/evidence.ts', out: 'supabase/functions/training-coach/evidence.generated.ts', claims: 'CLAIMS', refs: 'TRAINING_REFERENCES' },
  { src: 'src/lib/recovery/doctor/evidence.ts', out: 'supabase/functions/recovery-coach/evidence.generated.ts', claims: 'RECOVERY_CLAIMS', refs: 'RECOVERY_REFERENCES' },
];

for (const t of TARGETS) {
  const bundle = path.join(os.tmpdir(), `startfit-evidence-${process.pid}-${path.basename(path.dirname(t.out))}.mjs`);
  await esbuild.build({
    entryPoints: [path.join(root, t.src)],
    bundle: true,
    format: 'esm',
    platform: 'node',
    outfile: bundle,
    logLevel: 'error',
  });
  try {
    const mod = await import(pathToFileURL(bundle).href);
    const CLAIMS = mod[t.claims];
    const REFS = mod[t.refs];
    const claims = Object.values(CLAIMS).map((c) => ({
      id: c.id,
      kind: c.kind,
      text: c.text,
      refs: c.refs.map((r) => ({ short: REFS[r].short, url: REFS[r].url })),
    }));
    const out = path.join(root, t.out);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(
      out,
      `// Generated by scripts/generate-coach-evidence.mjs from ${t.src}: do not edit by hand.\n\n` +
        `export interface CoachClaim {\n  id: string;\n  kind: 'study' | 'design';\n  text: string;\n  refs: { short: string; url: string }[];\n}\n\n` +
        `export const COACH_CLAIMS: CoachClaim[] = ${JSON.stringify(claims, null, 2)};\n`,
    );
    console.log(`Wrote ${path.relative(root, out)} (${claims.length} claims).`);
  } finally {
    fs.rmSync(bundle, { force: true });
  }
}
