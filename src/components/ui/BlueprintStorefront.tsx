import { useState } from 'react';
import { Check, Crown, Loader2, X, FileText, Zap, Brain, Dumbbell, HeartPulse, FileDown } from 'lucide-react';
import { Modal } from '@/components/ui/Modal';
import { createBlueprintCheckout } from '@/lib/data';
import { BLUEPRINTS } from '@/lib/entitlements';
import { cn } from '@/lib/utils';

interface BlueprintStorefrontProps {
  open: boolean;
  onClose: () => void;
}

const INCLUDED_FEATURES = [
  { icon: Dumbbell, label: 'Custom Biomechanical Workout Routine', desc: 'Tailored daily workouts — sets, reps, rest timers & form cues calculated for your exact duration' },
  { icon: HeartPulse, label: 'Injury & Joint Adaptation', desc: 'Automated exercise swaps for joint issues or injuries powered by o3-mini' },
  { icon: Brain, label: 'Personalized Nutrition & Macro Targets', desc: 'Daily calories, protein, carbs, and fat breakdown matched to your goals' },
  { icon: FileDown, label: 'Downloadable Dark-Luxury PDF Export', desc: 'Instant high-resolution PDF to keep or print forever — zero recurring fees' },
];

export function BlueprintStorefront({ open, onClose }: BlueprintStorefrontProps) {
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const selected = BLUEPRINTS.find((b) => b.id === selectedId);

  const purchase = async () => {
    if (!selectedId) return;
    setLoading(true);
    setError(null);
    try {
      const url = await createBlueprintCheckout(selectedId);
      window.location.assign(url);
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : 'Unable to start checkout.');
      setLoading(false);
    }
  };

  return (
    <Modal open={open} onClose={onClose} className="sm:max-w-lg !p-0">
      <div className="flex items-start justify-between gap-4 mb-5">
        <div>
          <div className="flex items-center gap-2 text-lime mb-1">
            <FileText className="w-5 h-5" />
            <span className="text-xs font-bold uppercase tracking-widest">AI Blueprint Store</span>
          </div>
          <h2 className="text-display-md text-cloud font-bold">Buy a custom AI workout plan</h2>
          <p className="text-sm text-cloud-dim mt-1">
            One-off purchase. No subscription needed. Each blueprint is generated by the o3-mini reasoning engine based on your biometrics.
          </p>
        </div>
        <button onClick={onClose} className="text-cloud-dim hover:text-cloud transition-colors" aria-label="Close">
          <X className="w-5 h-5" />
        </button>
      </div>

      {/* What's included */}
      <div className="rounded-xl2 bg-ink-surface border border-ink-border p-3.5 mb-4 space-y-2.5">
        <p className="text-[10px] font-semibold text-cloud-dim uppercase tracking-wider">Every blueprint includes</p>
        {INCLUDED_FEATURES.map((f) => (
          <div key={f.label} className="flex items-start gap-2.5">
            <div className="w-7 h-7 rounded-lg bg-lime/10 flex items-center justify-center text-lime flex-shrink-0">
              <f.icon className="w-3.5 h-3.5" />
            </div>
            <div className="flex-1 min-w-0">
              <p className="text-xs font-semibold text-cloud">{f.label}</p>
              <p className="text-[10px] text-cloud-dim leading-snug">{f.desc}</p>
            </div>
          </div>
        ))}
      </div>

      {/* Blueprint options */}
      <div className="space-y-2.5 mb-5 max-h-[300px] overflow-y-auto">
        {BLUEPRINTS.map((bp) => (
          <button
            key={bp.id}
            onClick={() => setSelectedId(bp.id)}
            className={cn(
              'w-full flex items-center gap-3 p-3.5 rounded-xl2 border transition-all text-left',
              selectedId === bp.id
                ? 'border-lime/40 bg-lime/5'
                : 'border-ink-border bg-ink-surface hover:border-lime/20'
            )}
          >
            <div className={cn(
              'w-10 h-10 rounded-xl flex items-center justify-center flex-shrink-0 transition-colors',
              selectedId === bp.id ? 'bg-lime text-ink-bg' : 'bg-ink-elevated text-lime'
            )}>
              <Zap className="w-5 h-5" />
            </div>
            <div className="flex-1 min-w-0">
              <div className="flex items-center gap-2">
                <p className="text-sm font-semibold text-cloud">{bp.name}</p>
                {bp.weeks >= 12 && (
                  <span className="flex items-center gap-1 px-1.5 py-0.5 rounded-full bg-lime/15 text-lime text-[9px] font-bold">
                    <Brain className="w-2.5 h-2.5" /> BEST VALUE
                  </span>
                )}
              </div>
              <p className="text-[11px] text-cloud-dim leading-snug mt-0.5 line-clamp-2">{bp.description}</p>
            </div>
            <div className="text-right flex-shrink-0">
              <p className="text-sm font-bold text-cloud">£{bp.price.toFixed(2)}</p>
              <p className="text-[10px] text-cloud-dim">{bp.duration}</p>
            </div>
            {selectedId === bp.id && (
              <Check className="w-4 h-4 text-lime flex-shrink-0" />
            )}
          </button>
        ))}
      </div>

      {selected && (
        <div className="rounded-2xl bg-gradient-to-br from-lime/10 to-sky/5 border border-lime/20 p-4 mb-5 animate-fade-in">
          <div className="flex items-end justify-between mb-2">
            <div>
              <p className="text-xs text-cloud-dim">{selected.name}</p>
              <p className="text-3xl font-bold text-cloud">£{selected.price.toFixed(2)}</p>
            </div>
            <div className="text-right">
              <p className="text-[10px] text-cloud-dim">{selected.duration}</p>
              <p className="text-[10px] text-lime font-semibold">One-time payment</p>
            </div>
          </div>
        </div>
      )}

      {error && <p className="text-xs text-rust mb-3">{error}</p>}

      <button
        onClick={purchase}
        disabled={!selectedId || loading}
        className="w-full flex items-center justify-center gap-2 rounded-xl py-3.5 bg-lime-gradient text-ink-bg font-bold text-sm shadow-lime hover:brightness-105 disabled:opacity-40 transition-all"
      >
        {loading ? <Loader2 className="w-4 h-4 animate-spin" /> : <Crown className="w-4 h-4" />}
        {!selectedId ? 'Select a blueprint' : loading ? 'Opening secure checkout…' : `Buy ${selected?.name} — £${selected?.price.toFixed(2)}`}
      </button>
      <p className="text-center text-[10px] text-cloud-dim mt-3">One-time payment via Stripe. No recurring charges. PDF download included.</p>
    </Modal>
  );
}
