// Hand-reviewed corrections for the exercise library.
//
// Every exercise from the open dataset (free-exercise-db, "D:") and the app's own
// catalogue ("C:") was classified by src/lib/training/taxonomy.ts and then reviewed
// one by one. This file holds the outcome of that review:
//   - PROFILE_OVERRIDES: exercises whose automatic classification was wrong or incomplete
//   - DUPLICATES: catalogue entries that repeat a dataset exercise (hidden, kept as aliases)
//   - EXTRA_ALIASES: common names people search for
// It is used only when the library migration is generated (scripts/generate-training-library.mjs)
// and by the library tests; the app itself reads the stored result from the database.

import type { ExerciseProfile } from './taxonomy';

export interface ProfileOverride extends Partial<Omit<ExerciseProfile, 'confidence'>> {
  /** A clearer display name. */
  name?: string;
  /** Difficulty when the source's label is wrong. */
  difficulty?: 'beginner' | 'intermediate' | 'advanced';
  /** Technique steps for dataset entries that ship without any. */
  instructions?: string[];
  /** Hide from the library: the source entry is unusable (e.g. no instructions and ambiguous). */
  hidden?: true;
}

